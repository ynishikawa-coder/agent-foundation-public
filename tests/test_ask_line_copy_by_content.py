"""聞く線の写しを、字の形でなく中身で拾う注入の試験。

意図: 聞く線の正本は細目 §4 の 1 文だけにし、§3・§5 には写さず指すだけにする。
課題: 写しを「聞くのは…だけ」の字の形だけで拾っていたので、言い回しを変えた写し（「問う」「に限る」）は通っていた。
原因: 写しかを決める物が、正本の中身（合意の項目）でなく、1 つの言い回しの形だった。
ここでは、言い回しを変えた写しを §3・§5 に入れると赤になる事を見る。入力は作り物の文。
"""
from test_ask_only_on_line import _saimoku, saimoku_ok


def test_言い回しを変えた写しも拾う():
    """意図: 写しを形でなく中身で止める。課題: 「聞くのは…だけ」の形でない写しは通っていた。"""
    s03, s04, s05 = _saimoku()
    assert saimoku_ok(s03, s04, s05)
    for copy in ("\n- オーナーへ問うのは顧客側と要件に効く行に限る。",
                 "\n- お金・社外の時はオーナーに聞く。",
                 "\n- 仕上がりが変わる時はオーナーに確かめて問う。"):
        assert not saimoku_ok(s03 + copy, s04, s05), copy
        assert not saimoku_ok(s03, s04, s05 + copy), copy
