"""細目「聞き方」の 2 文（決まりの言葉が出そうな時の読み・窓を読まずに答えられる形）を照らす試験。

意図: オーナーは窓の中を読まずに、チャットと選択肢の画面だけで答えを決められる。
課題: 2 文は言い回しを縮めた時に、照らす試験が無いまま残っていた。
ここでは、2 文の中身（何を指す言葉か）が細目「聞き方」に在る事を見る。文を消すと赤になる。
"""
from pathlib import Path

S04 = Path(__file__).resolve().parents[1] / "plugins" / "core" / "細目" / "04-聞き方.md"


def _line(head):
    return next(s for s in S04.read_text(encoding="utf-8").splitlines() if s.startswith(f"- **{head}**"))


def test_決まりの言葉が出そうな時は_AI_が決める事か聞き方のずれと読む():
    """意図: 決まりの言葉を問いに出さない。課題: 出そうな時の読み方を照らす試験が無かった。"""
    line = _line("問いの言葉")
    assert "出そうなら AI が決める事か聞き方のずれ" in line


def test_窓を読んでいない人がチャットと画面だけで答えられる():
    """意図: 窓の中を読まずに答えられる。課題: この文を照らす試験が無く、守らない文の表の行は古い言い回しのままだった。"""
    line = _line("見せてから聞く")
    assert "窓を読んでいない人がチャットと画面だけで答えられる形に" in line
